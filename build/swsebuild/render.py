"""Markdown / TSV projections: the files an agent reads *before* it reads data.

Rule of thumb for each projection: it must be cheap enough to read whole, and it
must always answer "does X exist, and where is the text?" in one hop. Anything
longer than that belongs in ``data/`` or ``index/swse.db``, reached by grep/SQL.
"""

from __future__ import annotations

import collections
import json
import os

from . import util

MAX_LINE = 200


def m_links(ctx) -> int:
    return sum(len(p.get("link_targets") or []) for p in ctx.pages)


def _short(text: str, n: int = 110) -> str:
    t = util.squash(str(text or "").replace("|", "/").replace("`", "'"))
    if not t:
        return ""
    return t if len(t) <= n else t[: n - 1].rstrip(" ,;.") + "…"


def _cite(rec: dict) -> str:
    """Compact provenance pointer: file[:line]."""
    prov = rec.get("provenance") or {}
    f = prov.get("file") or rec.get("file") or ""
    ls = prov.get("line_start")
    le = prov.get("line_end")
    if prov.get("sheet"):
        return f"[{prov['source']}:{prov['sheet']}!r{prov.get('row')}]"
    if f and ls:
        return f"`{f}:{ls}`"
    if f:
        return f"`{f}`"
    return ""


