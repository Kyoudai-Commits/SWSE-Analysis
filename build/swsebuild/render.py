def coverage_md(ctx: dict) -> str:
    cov = ctx.coverage
    out = [
        "# Coverage & reconciliation",
        "",
        "How complete this knowledge base is, per entity family and per source, and what the",
        "three inputs disagree about. **Read this before trusting a negative answer.**",
        "",
        "## By entity family",
        "",
        "| family | entities | with wiki page | spreadsheet-only | pages | chars |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for fam, st in cov["by_type"].items():
        ent = st.get("entities", 0)
        withp = st.get("with_wiki_page", 0)
        out.append(f"| `{fam}` | {ent:,} | {withp:,} | {ent - withp:,} | {st.get('pages', 0):,} | {st.get('chars', 0):,} |")
    out += [
        "",
        "## By source book",
        "",
        "| book | pages | feats | talents | force powers |",
        "| --- | --- | --- | --- | --- |",
    ]
    for book, st in cov["by_book"].items():
        out.append(
            f"| {book} | {st.get('pages', 0):,} | {st.get('feats', 0):,} | {st.get('talents', 0):,} | {st.get('force_powers', 0):,} |"
        )
    out += [
        "",
        "## Source cross-check",
        "",
        "| check | count | meaning |",
        "| --- | --- | --- |",
    ]
    for label, n, note in ctx.xcheck:
        out.append(f"| {label} | {n:,} | {note} |")
    out += [
        "",
        "## Known limits",
        "",
        "- **Equipment stats are thin.** The crawl captured rulebook *chapter intros* (`Category:Weapons`,",
        "  `Category:Armor`) and only a handful of item pages; full weapon/armor/starship/vehicle stat",
        "  blocks live on uncrawled pages (see `crawl-backlog.md`) or in `3rd_Party_Builder/` only.",
        "- **No page numbers from the wiki.** Only SagaForge carries book+page citations (its `Page` column),",
        "  so book-level citation for wiki-only records stops at the source book, not the page.",
        "- **Droids / starships / vehicles / planets are index-shaped**, not stat-shaped: the pages exist as",
        "  lists that point at uncrawled targets.",
        "- **Raw spreadsheets are form UIs**, so `3rd_Party_Builder/` coverage is limited to the four",
        "  rectangular sheets this build parses (`Feats`, `Talents`, `ForcePowerCards`, `NewStatBlockRef`) plus",
        "  the `Data` sheet's book-abbreviation legend. The other 26 sheets are character-calculation forms.",
        "",
    ]
    return "\n".join(out)


def discrepancies_md(ctx: dict) -> str:
    rows = ctx.diffs
    out = [
        "# Cross-source discrepancies",
        "",
        f"{len(rows):,} field-level disagreements between the wiki, `SWSE_Master_Reference` and `SagaForge`,",
        "after ignoring punctuation, word order, and abbreviation differences. Do not silently pick",
        "a winner: quote the sources that disagree.",
        "",
        "Severity: **value** = the numbers or content words disagree; **wording** =",
        "paraphrase or abbreviation (e.g. `BAB +6` vs `Base Attack Bonus +6`). Only",
        "`value` conflicts raise the `has-field-diffs` flag on a record.",
        "",
        "| entity | field | severity | per-source values |",
        "| --- | --- | --- | --- |",
    ]
    for ent_id, name, field, values, severity in rows[:1200]:
        pretty = " · ".join(f"**{s}:** {_short(v, 90)}" for s, v in sorted(values.items()))
        out.append(f"| {name} (`{ent_id}`) | `{field}` | {severity} | {pretty} |")
    if len(rows) > 1500:
        out.append(f"| … | | _{len(rows) - 1500:,} more in `data/discrepancies.jsonl`_ |")
    out += [
        "",
        "_Full machine-readable list: `data/discrepancies.jsonl`._",
        "",
    ]
    return "\n".join(out)


def backlog_md(ctx: dict) -> str:
    hard = [g for g in ctx.gaps if not g.get("approx_to")]
    soft = [g for g in ctx.gaps if g.get("approx_to")]
    hard_slugs = {g["target_slug"] for g in hard}
    hard.extend(g for g in soft if False)
    gaps = hard
    by_kind = collections.Counter(g["kind"] for g in gaps)
    out = [
        "# Crawl backlog (referenced but not in this corpus)",
        "",
        f"{len(gaps):,} distinct link targets are cited by the corpus but have no page here,",
        f"accounting for {sum(g['refs'] for g in gaps):,} of the {m_links(ctx):,} internal links.",
        "Ranked by how often the corpus leans on them — i.e. the exact list to fetch next, in order.",
        "",
        f"Kind breakdown: " + ", ".join(f"`{k}` {n:,}" for k, n in by_kind.most_common()) + ".",
        "",
        "Reading the columns: **refs** = link instances, **pages** = distinct pages needing it,",
        "**in manifest** = the URL also appears in `SWSE_Master_Reference`'s `Links` sheet (it was",
        "intended to be crawled and was not).",
        "",
        "| # | target | kind | refs | pages | in manifest | example citing pages |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    manifest_slugs = getattr(ctx, "manifest_norms", set())
    for i, g in enumerate(hard[:400], 1):
        inman = "yes" if g["norm"] in manifest_slugs else "—"
        out.append(
            f"| {i} | `{g['target_slug']}` | {g['kind']} | {g['refs']} | {g['n_pages']} | {inman} | "
            f"{', '.join(p.replace('wiki:', '') for p in g['sample_pages'][:3])} |"
        )
    out += [
        "",
        f"_Top 400 of {len(hard):,} shown; complete machine-readable version: `index/crawl-backlog.tsv`._",
        "",
        "Coverage of just the top 100 rows ≈ half of all dangling link instances, so a small",
        "follow-up crawl (100–150 pages) closes most of the gap; the long tail is mostly",
        "proper nouns (people, worlds, ships) that the rules text rarely needs.",
        "",
        f"## Covered only approximately ({len(soft):,} targets, {sum(g['refs'] for g in soft):,} refs)",
        "",
        "These names have no page of their own, but the corpus has text that answers them",
        "(the wiki anchors per-variant names at a parent article — e.g. *Weapon Focus",
        "(Lightsabers)* → `Weapon_Focus`). They are real coverage, **flagged rather than",
        "hidden**: cite the parent page, and treat it as lower-priority crawling work.",
        "",
        "| target | refs | approximated by |",
        "| --- | --- | --- |",
    ]
    for g in soft[:120]:
        out.append(f"| `{g['target_slug']}` | {g['refs']} | `{g['approx_to']}` ({g['approx_by']}) |")
    if len(soft) > 120:
        out.append(f"| … | | _{len(soft) - 120:,} more in `index/crawl-backlog.tsv` (rows with a non-empty `approx_to`)_ |")
    out.append("")
    return "\n".join(out)


def aliases_tsv(path: str, aliases: list[dict]) -> int:
    rows = ["alias\talias_norm\ttarget_id\ttarget_type\tkind"]
    for a in aliases:
        rows.append("\t".join([a["alias"], a["alias_norm"], a["target_id"], a["target_type"], a["kind"]]))
    util.write_text(path, "\n".join(rows) + "\n")
    return len(rows) - 1


def gaps_tsv(path: str, gaps: list[dict], manifest_norms: set) -> int:
    rows = ["rank\ttarget_slug\tguess\tkind\trefs\tn_pages\tin_master_reference_manifest\tapprox_to\tapprox_by\tsample_pages"]
    for i, g in enumerate(gaps, 1):
        rows.append(
            "\t".join(
                [
                    str(i),
                    g["target_slug"],
                    g["guess"],
                    g["kind"],
                    str(g["refs"]),
                    str(g["n_pages"]),
                    "yes" if g["norm"] in manifest_norms else "no",
                    g.get("approx_to", ""),
                    g.get("approx_by", ""),
                    " ".join(g["sample_pages"][:5]),
                ]
            )
        )
    util.write_text(path, "\n".join(rows) + "\n")
    return len(rows) - 1
