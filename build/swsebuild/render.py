def by_type_files(out_dir: str, entities: list[dict], root: str) -> list[str]:
    by_fam: dict[str, list[dict]] = collections.defaultdict(list)
    for e in entities:
        by_fam[e["family"]].append(e)
    written = []
    for fam, rows in sorted(by_fam.items()):
        rows.sort(key=lambda e: e["name"].lower())
        head = [
            f"# {fam} — {len(rows):,} records",
            "",
            f"_One line per record. Grep this file; open the cited file for the rule text._",
            "",
            "| name | key | detail | books | cite |",
            "| --- | --- | --- | --- | --- |",
        ]
        body = []
        for e in rows:
            detail = _detail_for(e)
            books = ", ".join(_abbr(b) for b in (e.get("books") or [])) or "—"
            flags = e.get("flags") or []
            mark = ""
            if "no-wiki-page" in flags:
                mark = " ⚠︎uncrawled"
            elif "has-field-diffs" in flags:
                mark = " ⚠︎conflict"
            body.append(
                f"| **{e['name']}** | `{e['id']}`{mark} | {_short(detail, 96)} | {_short(books, 40)} | {_cite(e)} |"
            )
        text = "\n".join(head + body) + "\n"
        path = os.path.join(out_dir, f"{util.kebab(fam)}.md")
        util.write_text(path, text)
        written.append(util.rel(root, path))
    return written


_DETAIL_FIELD_ORDER = {
    "feat": ["prerequisites", "benefit"],
    "talent": ["prerequisites", "benefit"],
    "talent-tree": ["availability", "prerequisites", "benefit"],
    "force-power": ["power_type", "action_time", "benefit", "descriptors", "target"],
    "species": ["ability_modifiers", "size", "speed", "languages"],
    "heroic-class": ["hit_points", "defense_bonus", "trained_skills", "class_skills"],
    "prestige-class": ["prerequisites", "min_level"],
    "weapon": ["weapon_group", "damage", "cost_credits", "stun_setting", "rate_of_fire", "weight_kg"],
    "armor": ["defense_bonus", "armor_check_penalty", "speed", "cost_credits"],
    "equipment": ["cost_credits", "weight_kg", "skill"],
    "class-ability": ["action", "tags", "benefit", "source"],
    "droid": ["cost_credits", "skills", "programs", "size"],
    "creature": ["size", "speed", "initiative", "perception"],
    "starship": ["scale", "cost_credits", "maneuverability", "hyperdrive"],
    "vehicle": ["speed", "defense", "hp"],
    "planet": ["population", "government", "languages"],
    "affiliation": ["benefit", "requirements"],
}


def _detail_for(e: dict) -> str:
    fields = e.get("fields") or {}
    order = _DETAIL_FIELD_ORDER.get(e["family"], ["prerequisites", "benefit"])
    parts = [fields[k] for k in order if fields.get(k)]
    if not parts:
        parts = [e.get("summary") or ""]
    return " · ".join(_short(p, 70) for p in parts[:3])


_ABBR_CACHE: dict[str, str] = {}


def _abbr(book: str) -> str:
    if not _ABBR_CACHE:
        from .sources import BOOK_ABBREVS

        _ABBR_CACHE.update({v: k for k, v in BOOK_ABBREVS.items()})
    return _ABBR_CACHE.get(book, book)


def by_book_files(out_dir: str, pages: list[dict], entities: list[dict], root: str) -> list[str]:
    """Per-source-book contents: what this book contributed to the corpus."""
    pages_by_book: dict[str, list[dict]] = collections.defaultdict(list)
    ents_by_book: dict[str, list[dict]] = collections.defaultdict(list)
    for p in pages:
        for b in [c for c in p.get("categories") or [] if _looks_like_book(c)]:
            pages_by_book[b].append(p)
    for e in entities:
        for b in e.get("books") or []:
            ents_by_book[b].append(e)
    written = []
    for book in sorted(set(pages_by_book) | set(ents_by_book)):
        pgs, ents = pages_by_book.get(book, []), ents_by_book.get(book, [])
        counts = collections.Counter(e["family"] for e in ents)
        head = [
            f"# {book}",
            "",
            f"_Contributions found in this corpus: {len(pgs):,} pages, {len(ents):,} entities._",
            "",
            "| family | count |",
            "| --- | --- |",
        ]
        head += [f"| `{fam}` | {n:,} |" for fam, n in counts.most_common(20)]
        body = ["", "## Pages", "", "| title | type | file |", "| --- | --- | --- |"]
        for p in sorted(pgs, key=lambda x: x["title"].lower()):
            body.append(f"| {p['title']} | {p['type']} | `{p['file']}` |")
        path = os.path.join(out_dir, f"{util.kebab(book)}.md")
        util.write_text(path, "\n".join(head + body) + "\n")
        written.append(util.rel(root, path))
    return written


def _looks_like_book(cat: str) -> bool:
    import re as _re

    return bool(
        _re.search(r"(Campaign Guide|Rulebook|Training Manual)$", cat)
        or cat
        in {
            "Core Rulebook",
            "Scum and Villainy",
            "Threats of the Galaxy",
            "Starships of the Galaxy",
            "Galaxy at War",
            "Galaxy of Intrigue",
            "Web Enhancements",
            "Saga Edition FAQ",
            "Scavenger's Guide to Droids",
            "Unknown Regions Campaign Guide",
        }
    )


def by_class_files(out_dir: str, pages: list[dict], entities: list[dict], classes: list[dict], root: str) -> list[str]:
    """Per heroic class: bonus feats and talent trees, from the wiki's own tags."""
    by_class_ent: dict[str, list[dict]] = collections.defaultdict(list)
    for e in entities:
        for c in e.get("categories") or []:
            if c.endswith("Bonus Feats"):
                by_class_ent[c[: -len(" Bonus Feats")].strip()].append(e)
            elif c.endswith(" Talent Trees"):
                by_class_ent[c[: -len(" Talent Trees")].strip()].append(e)
    written = []
    names = sorted({c["name"] for c in classes} | set(by_class_ent))
    for cls in names:
        rows = by_class_ent.get(cls, [])
        feats = [e for e in rows if e["family"] == "feat"]
        trees = [e for e in rows if e["family"] == "talent-tree"]
        spec = next((c for c in classes if util.norm_name(c["name"]) == util.norm_name(cls)), None)
        head = [f"# {cls}", ""]
        if spec:
            f = spec.get("fields") or {}
            head += [
                f"- **Starting HP:** {f.get('hit_points', '—')} · **Trained skills:** {f.get('trained_skills', '—')}",
                f"- **Defenses:** {_short(f.get('defense_bonus', '—'), 40)}",
                f"- **Starting feats:** {', '.join(util.split_list(f.get('starting_feats', ''))) or '—'}",
                f"- **Talent trees:** {', '.join(util.split_list(f.get('talent_trees', ''))) or '—'}",
                f"- **Class skills:** {', '.join(util.split_list(f.get('class_skills', '')))}",
                "",
            ]
        head += [
            f"## Bonus feats tagged for {cls} ({len(feats)})",
            "",
            "| feat | prerequisites | books | cite |",
            "| --- | --- | --- | --- |",
        ]
        for e in sorted(feats, key=lambda x: x["name"].lower()):
            head.append(
                f"| **{e['name']}** | {_short(', '.join(e.get('prerequisites') or []) or '—', 70)} | "
                f"{_short(', '.join(_abbr(b) for b in e.get('books') or []) or '—', 34)} | {_cite(e)} |"
            )
        head += ["", f"## Talent trees ({len(trees)})", "", "| tree | file |", "| --- | --- |"]
        for e in sorted(trees, key=lambda x: x["name"].lower()):
            head.append(f"| **{e['name']}** | {e.get('file') or _cite(e)} |")
        path = os.path.join(out_dir, f"{util.kebab(cls)}.md")
        util.write_text(path, "\n".join(head) + "\n")
        written.append(util.rel(root, path))
    return written


